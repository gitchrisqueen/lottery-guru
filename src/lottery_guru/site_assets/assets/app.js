/* Lottery Guru dashboard — vanilla JS, no dependencies, no build step.
   Reads the JSON payloads generated by `lottery-guru site` from ./data/.
   z≈0 is the expected result of the experiment; the z shading is symmetric
   in |z| and deliberately never reads as "winning".

   Display parity rule: numbers arrive from Python already rounded to the
   precision the markdown reports display — this file must never re-round
   (JS rounds half-away-from-zero, Python rounds half-even). */
"use strict";

const Z_CLAMP = 3; // |z| at which the gradient saturates

// ---------- storage (blocked-storage browsers must not break the page) ----------
function storageGet(key) {
  try { return localStorage.getItem(key); } catch { return null; }
}
function storageSet(key, value) {
  try { localStorage.setItem(key, value); } catch { /* non-persistent */ }
}

// ---------- theme ----------
(function initTheme() {
  const toggle = document.getElementById("theme-toggle");
  const apply = (theme) => {
    document.documentElement.dataset.theme = theme;
    toggle.setAttribute("aria-pressed", theme === "dark" ? "true" : "false");
    toggle.setAttribute("aria-label",
      theme === "dark" ? "Switch to light theme" : "Switch to dark theme");
  };
  const stored = storageGet("lg-theme");
  const prefersDark = window.matchMedia("(prefers-color-scheme: dark)").matches;
  apply(stored || (prefersDark ? "dark" : "light"));
  toggle.addEventListener("click", () => {
    const next = document.documentElement.dataset.theme === "dark" ? "light" : "dark";
    apply(next);
    storageSet("lg-theme", next);
  });
})();

// ---------- tabs (roving tabindex + arrow keys, per the ARIA tabs pattern) ----------
(function initTabs() {
  const tabs = Array.from(document.querySelectorAll(".tab"));
  const select = (tab) => {
    tabs.forEach((t) => {
      const active = t === tab;
      t.classList.toggle("active", active);
      t.setAttribute("aria-selected", active ? "true" : "false");
      t.tabIndex = active ? 0 : -1;
    });
    document.querySelectorAll(".panel").forEach((p) => {
      const active = p.id === `panel-${tab.dataset.panel}`;
      p.classList.toggle("active", active);
      p.hidden = !active;
    });
  };
  tabs.forEach((tab, i) => {
    tab.tabIndex = tab.classList.contains("active") ? 0 : -1;
    tab.addEventListener("click", () => select(tab));
    tab.addEventListener("keydown", (e) => {
      let target = null;
      if (e.key === "ArrowRight") target = tabs[(i + 1) % tabs.length];
      else if (e.key === "ArrowLeft") target = tabs[(i - 1 + tabs.length) % tabs.length];
      else if (e.key === "Home") target = tabs[0];
      else if (e.key === "End") target = tabs[tabs.length - 1];
      if (target) {
        e.preventDefault();
        target.focus();
        select(target);
      }
    });
  });
})();

// ---------- helpers ----------
const esc = (s) =>
  String(s).replace(/[&<>"']/g, (c) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  }[c]));

// Thousands separators for integers only — never used to round decimals.
const fmtInt = (n) => Number(n).toLocaleString("en-US", { maximumFractionDigits: 0 });

const signed = (z) => (z > 0 ? `+${z}` : String(z));

const zT = (z) => Math.min(Math.abs(z), Z_CLAMP) / Z_CLAMP;

function zCell(z) {
  // Renders the payload value verbatim (already rounded server-side).
  return `<td class="z-cell num" style="--t:${zT(z).toFixed(3)}" data-value="${z}">${signed(z)}</td>`;
}

function balls(numbers, special, kind, actual) {
  // `actual` (jackpot: a Set with .specialHit; digit: {positional}) marks
  // predicted balls that matched. Hits carry a non-color cue (underline +
  // hidden text) so the state survives grayscale and screen readers.
  if (!numbers) return "—";
  const cls = kind === "digit" ? "balls digit-row" : "balls";
  let html = `<span class="${cls}">`;
  numbers.forEach((n, i) => {
    let hit = false;
    if (actual) {
      hit = kind === "jackpot" ? actual.has(n) : actual.positional[i] === n;
    }
    const pad = kind === "jackpot" ? String(n).padStart(2, "0") : String(n);
    html += `<span class="ball${hit ? " hit" : ""}">${pad}${hit ? '<span class="vh"> (matched)</span>' : ""}</span>`;
  });
  if (special !== null && special !== undefined) {
    const hit = actual && actual.specialHit;
    html += `<span class="ball special${hit ? " hit" : ""}">` +
      `${String(special).padStart(2, "0")}<span class="vh"> (special ball${hit ? ", matched" : ""})</span></span>`;
  }
  return html + "</span>";
}

// ---------- sortable tables ----------
function makeSortable(table) {
  table.querySelectorAll("th[data-sort]").forEach((th, idx) => {
    // A real button gets Enter/Space and a button role for free.
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "sort-btn";
    btn.innerHTML = th.innerHTML + '<span class="vh">, sortable column</span>';
    th.textContent = "";
    th.appendChild(btn);
    btn.addEventListener("click", () => {
      const current = th.getAttribute("aria-sort");
      table.querySelectorAll("th").forEach((h) => h.removeAttribute("aria-sort"));
      const dir = current === "descending" ? "ascending" : "descending";
      th.setAttribute("aria-sort", dir);
      sortTable(table, idx, th.dataset.sort === "num", dir === "ascending");
    });
  });
}

function sortTable(table, colIdx, numeric, asc) {
  const tbody = table.tBodies[0];
  const rows = Array.from(tbody.rows);
  rows.sort((a, b) => {
    const cellA = a.cells[colIdx], cellB = b.cells[colIdx];
    const va = cellA.dataset.value ?? cellA.textContent.trim();
    const vb = cellB.dataset.value ?? cellB.textContent.trim();
    let cmp;
    if (numeric) cmp = (parseFloat(va) || 0) - (parseFloat(vb) || 0);
    else cmp = String(va).localeCompare(String(vb));
    return asc ? cmp : -cmp;
  });
  rows.forEach((r) => tbody.appendChild(r));
}

// ---------- data loading ----------
async function loadJSON(name) {
  const res = await fetch(`data/${name}.json`);
  if (!res.ok) throw new Error(`${name}.json: ${res.status}`);
  return res.json();
}

// ---------- scoreboard ----------
function renderScoreboard(data) {
  const s = data.overall;
  document.getElementById("scoreboard-summary").innerHTML =
    `<strong>${fmtInt(s.n)}</strong> predictions scored across <strong>${fmtInt(s.days)}</strong> days. ` +
    `Combined, they've hit <strong>${fmtInt(s.observed)}</strong> numbers where pure chance predicts ` +
    `<strong>${s.expected.toFixed(1)}</strong> (z = <strong>${signed(s.z.toFixed(2))}</strong>).`;

  const tbody = document.querySelector("#scoreboard-table tbody");
  tbody.innerHTML = data.strategies.map((row) => `
    <tr data-strategy="${esc(row.strategy)}">
      <td data-value="${esc(row.strategy)}"><span class="strategy-name">${esc(row.strategy)}</span></td>
      <td class="num" data-value="${row.n}">${fmtInt(row.n)}</td>
      <td class="num" data-value="${row.observed}">${fmtInt(row.observed)}</td>
      <td class="num" data-value="${row.expected}">${row.expected.toFixed(1)}</td>
      <td class="num" data-value="${row.hit_rate}">${row.hit_rate.toFixed(2)}/draw</td>
      ${zCell(row.z.toFixed(2))}
      <td class="num" data-value="${row.best}">${row.best}${row.best_game ? ` <span class="best-game">(${esc(row.best_game)})</span>` : ""}</td>
    </tr>`).join("");

  makeSortable(document.getElementById("scoreboard-table"));

  document.getElementById("scoreboard-filter").addEventListener("input", (e) => {
    const q = e.target.value.trim().toLowerCase();
    tbody.querySelectorAll("tr").forEach((tr) => {
      tr.hidden = q && !tr.dataset.strategy.toLowerCase().includes(q);
    });
  });
}

// ---------- per-game leaderboards ----------
function renderLeaderboards(data) {
  const select = document.getElementById("game-select");
  const container = document.getElementById("leaderboard-container");
  const keys = Object.keys(data.games);
  if (!keys.length) {
    select.closest(".select-label").hidden = true;
    container.innerHTML = `<p class="empty-note">No scored predictions yet — leaderboards appear once drawings come in.</p>`;
    return;
  }
  select.innerHTML = keys.map((k) =>
    `<option value="${esc(k)}">${esc(data.games[k].display)}</option>`).join("");

  const show = (key) => {
    const g = data.games[key];
    // Observed/Expected/z/p render verbatim — same values REPORT.md prints.
    container.innerHTML = `
      <div class="game-board">
        <h3>${esc(g.display)} <span class="kind-tag">${esc(g.kind)}</span></h3>
        <p class="null-line">Null expectation: ${g.null_expectation.toFixed(4)} matches per prediction.</p>
        <div class="table-scroll">
          <table class="data-table" id="lb-table">
            <thead><tr>
              <th data-sort="str">Strategy</th>
              <th data-sort="num">n</th>
              <th data-sort="num">Observed</th>
              <th data-sort="num">Expected</th>
              <th data-sort="num" aria-sort="descending">z</th>
              <th data-sort="num">p</th>
              <th data-sort="num">Straights</th>
            </tr></thead>
            <tbody>${g.rows.map((r) => `
              <tr>
                <td data-value="${esc(r.strategy)}"><span class="strategy-name">${esc(r.strategy)}</span></td>
                <td class="num" data-value="${r.n}">${fmtInt(r.n)}</td>
                <td class="num" data-value="${r.observed_matches}">${fmtInt(r.observed_matches)}</td>
                <td class="num" data-value="${r.expected_matches}">${r.expected_matches}</td>
                ${zCell(r.z)}
                <td class="num" data-value="${r.p_value}">${r.p_value}</td>
                <td class="num" data-value="${r.straights}">${fmtInt(r.straights)}</td>
              </tr>`).join("")}
            </tbody>
          </table>
        </div>
      </div>`;
    makeSortable(container.querySelector("#lb-table"));
  };

  select.addEventListener("change", () => show(select.value));
  show(keys[0]);
}

// ---------- today's picks ----------
function renderPicks(data) {
  const container = document.getElementById("picks-container");
  const select = document.getElementById("picks-game-select");
  if (!data.date || !data.groups.length) {
    container.innerHTML = `<p class="empty-note">No predictions recorded yet.</p>`;
    select.closest(".select-label").hidden = true;
    return;
  }
  document.getElementById("picks-heading").textContent = `Picks for ${data.date}`;

  const gameKeys = [...new Set(data.groups.map((g) => g.game))];
  select.innerHTML = `<option value="">All games</option>` + gameKeys.map((k) => {
    const display = data.groups.find((g) => g.game === k).display;
    return `<option value="${esc(k)}">${esc(display)}</option>`;
  }).join("");

  const render = (filterKey) => {
    container.innerHTML = data.groups
      .filter((g) => !filterKey || g.game === filterKey)
      .map((group) => {
        const title = group.draw_time === "main"
          ? group.display : `${group.display} — ${group.draw_time}`;
        const scored = group.scored;
        const head = scored
          ? "<th>Strategy</th><th>Predicted</th><th>Actual</th><th>Matches</th>"
          : "<th>Strategy</th><th>Predicted</th>";
        const rows = group.rows.map((r) => {
          let actualCtx = null;
          if (r.actual_numbers) {
            actualCtx = group.kind === "jackpot"
              ? Object.assign(new Set(r.actual_numbers), { specialHit: !!r.special_hit })
              : { positional: r.actual_numbers, specialHit: false };
          }
          const predicted = balls(r.predicted_numbers, r.predicted_special, group.kind, actualCtx);
          if (!scored) {
            return `<tr><td><span class="strategy-name">${esc(r.strategy)}</span></td><td>${predicted}</td></tr>`;
          }
          const actual = r.actual_numbers
            ? balls(r.actual_numbers, r.actual_special, group.kind, null) : "—";
          let marks = r.matches === null ? "—" : String(r.matches);
          if (r.special_hit) marks += " +special";
          if (r.straight) marks += " (straight)";
          return `<tr>
            <td><span class="strategy-name">${esc(r.strategy)}</span></td>
            <td>${predicted}</td><td>${actual}</td>
            <td class="num" data-value="${r.matches ?? -1}">${marks}</td>
          </tr>`;
        }).join("");
        return `
          <div class="picks-group">
            <h3>${esc(title)} <span class="kind-tag">${esc(group.kind)}</span></h3>
            <div class="table-scroll">
              <table class="data-table"><thead><tr>${head}</tr></thead><tbody>${rows}</tbody></table>
            </div>
          </div>`;
      }).join("");
  };

  select.addEventListener("change", () => render(select.value));
  render("");
}

// ---------- exploit watch ----------
function renderExploit(data) {
  document.getElementById("exploit-note").textContent = data.note;
  const tbody = document.querySelector("#exploit-table tbody");
  tbody.innerHTML = data.rows.map((r) => `
    <tr>
      <td data-value="${esc(r.display)}">${esc(r.display)}</td>
      <td class="num" data-value="${r.combinations}">${fmtInt(r.combinations)}</td>
      <td class="num" data-value="${r.buyout_cost}">$${fmtInt(r.buyout_cost)}</td>
      <td class="num" data-value="${r.break_even_jackpot}">$${fmtInt(r.break_even_jackpot / 1e6)}M</td>
      <td data-value="${r.rolldown_defect ? 1 : 0}">${r.rolldown_defect ? "⚠ flagged" : "none"}</td>
    </tr>`).join("");
  makeSortable(document.getElementById("exploit-table"));
}

// ---------- boot ----------
(async function boot() {
  try {
    const [meta, scoreboard, leaderboard, predictions, monitors] = await Promise.all([
      loadJSON("meta"), loadJSON("scoreboard"), loadJSON("leaderboard"),
      loadJSON("predictions"), loadJSON("monitors"),
    ]);
    document.getElementById("updated-stamp").textContent = `Updated ${meta.generated_at}`;
    if (scoreboard.strategies.length) renderScoreboard(scoreboard);
    else document.getElementById("scoreboard-summary").innerHTML =
      `<span class="empty-note">No predictions scored yet — stats appear once drawings come in.</span>`;
    renderLeaderboards(leaderboard);
    renderPicks(predictions);
    renderExploit(monitors);
  } catch (err) {
    document.querySelector("main").insertAdjacentHTML("afterbegin",
      `<p class="empty-note">Could not load dashboard data (${esc(err.message)}). ` +
      `If you opened this file directly, serve it over HTTP instead.</p>`);
  }
})();
